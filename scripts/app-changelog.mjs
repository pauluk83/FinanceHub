/**
 * Build-time application changelog.
 *
 * Reads CHANGELOG.md, stamps it with the package version, a deterministic source
 * build id and the build time, then writes app/src/appChangelog.generated.ts.
 * The npm pre-build hooks run it for both the hosted and desktop bundles, so the
 * login page, the in-app changelog and the Windows app always describe the same
 * build. Tests import the exported helpers.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Parse `## [version] — date` sections with `### Heading` bullet lists. */
export function parseChangelog(text) {
  const releases = [];
  let current = null;
  let section = null;
  for (const line of text.split(/\r?\n/)) {
    const release = line.match(/^##\s+\[([^\]]+)\]\s*[—–-]\s*(.+)$/);
    if (release) {
      current = { version: release[1].trim(), date: release[2].trim(), sections: [] };
      releases.push(current);
      section = null;
      continue;
    }
    if (!current) continue;
    const heading = line.match(/^###\s+(.+)$/);
    if (heading) {
      section = { title: heading[1].trim(), items: [] };
      current.sections.push(section);
      continue;
    }
    const item = line.match(/^[-*]\s+(.+)$/);
    if (item && section) section.items.push(item[1].trim());
  }
  return releases.filter((release) => release.sections.some((part) => part.items.length > 0));
}

function sourceFiles(dir) {
  const found = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) found.push(...sourceFiles(full));
    else if (/\.(ts|tsx|cjs)$/.test(entry) && !entry.endsWith('.generated.ts')) found.push(full);
  }
  return found;
}

/** Deterministic id for a source tree: the same code gives the same id everywhere. */
export function buildId(root = ROOT) {
  const hash = createHash('sha256');
  const files = [
    ...sourceFiles(join(root, 'app', 'src')),
    ...sourceFiles(join(root, 'core')),
    ...sourceFiles(join(root, 'electron')),
    join(root, 'package.json'),
  ].sort();
  for (const file of files) {
    hash.update(relative(root, file).split(sep).join('/'));
    hash.update('\0');
    hash.update(readFileSync(file));
    hash.update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

export function buildAppChangelog({ root = ROOT, builtAt = new Date().toISOString().slice(0, 10) } = {}) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const releases = parseChangelog(readFileSync(join(root, 'CHANGELOG.md'), 'utf8'));
  if (releases.length === 0) throw new Error('CHANGELOG.md has no release sections');
  return { version: pkg.version, buildId: buildId(root), builtAt, releases };
}

function render(changelog) {
  return `// Generated by scripts/app-changelog.mjs from CHANGELOG.md — do not edit.
export interface AppChangelogSection { title: string; items: string[] }
export interface AppChangelogRelease { version: string; date: string; sections: AppChangelogSection[] }
export interface AppChangelog { version: string; buildId: string; builtAt: string; releases: AppChangelogRelease[] }

export const APP_CHANGELOG: AppChangelog = ${JSON.stringify(changelog, null, 2)};
`;
}

export function writeAppChangelog(options = {}) {
  const root = options.root ?? ROOT;
  const changelog = buildAppChangelog({ ...options, root });
  const target = join(root, 'app', 'src', 'appChangelog.generated.ts');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, render(changelog));
  return { target, changelog };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { target, changelog } = writeAppChangelog();
  console.log(`app changelog: ${changelog.version} build ${changelog.buildId}, ${changelog.releases.length} releases → ${relative(ROOT, target)}`);
}
